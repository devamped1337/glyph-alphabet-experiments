"""Reviewer tables + per-query JSONL from results/*.json -> results/EXTRA_TABLES_v5.md, results/predictions_{rk}.jsonl"""
import json, collections, os
O = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results"); L = lambda f: json.load(open(os.path.join(O, f)))
G, FZ = L("gate5.json"), L("frozen5.json"); md = ["# v5 reviewer tables (generated by extra5.py)", ""]
md += ["## Prose gate (rule A, DEV, prose >= 0.90 and none < 0.90)", "", "| receiver | task | prose | none | n | counted |", "|---|---|---|---|---|---|"]
for rk, d in FZ["task_gate_detail"].items():
    for t, v in d.items(): md.append(f"| {rk} | {t} | {v['prose']:.3f} | {v['none']:.3f} | {v['n']} | {'yes' if t in FZ['counted'][rk] else 'DROPPED'} |")
md += ["", "## Planted bad entries (all must be rejected)", "", "| depth | entry | rejected | failed checks | collateral rejections |", "|---|---|---|---|---|"]
for k, v in G["planted"].items():
    li, s = k.split("|"); md.append(f"| {li} | {s} | {'yes' if not v['pass'] else 'NO'} | {', '.join(c for c, ok in v['checks'].items() if not ok)} | {', '.join(v['collateral_rejections']) or '-'} |")
md += ["", "## Leave-one-out gate, per held-out entry", "", "| depth | symbol | held entries passing / total | failed checks (per entry) | collateral |", "|---|---|---|---|---|"]
tp = tn = 0
for k, v in G["loo"].items():
    li, s = k.split("|"); hp = v["held_entries_pass"]; p = sum(hp.values()); tp += p; tn += len(hp)
    fc = "; ".join(f"{e.split('|',1)[1]}: {','.join(c)}" for e, c in v.get("held_failed_checks", {}).items() if c)
    md.append(f"| {li} | {s} | {p}/{len(hp)} | {fc or '-'} | {', '.join(v.get('collateral_rejections', [])) or '-'} |")
md += ["", f"LOO gate pass rate over all held entries: {tp}/{tn} = {tp/max(tn,1):.3f}", ""]
CONDS = ["glyph_id", "glyph_id[random]", "null_randorth", "null_shufpair", "glyph_samenorm_shuffled", "glyph_raw_unsnapped", "receiver_word_state", "id_text_expanded", "id_text_raw", "text_prose", "text_compact", "text_bag", "none", "glyph_loo"]
for rk in ("smol", "qwen"):
    R = L(f"test_{rk}.json")["rows"]
    with open(os.path.join(O, f"predictions_{rk}.jsonl"), "w") as f:
        for r in R: f.write(json.dumps({"receiver": rk, **r}) + "\n")
    T = collections.defaultdict(list)
    for r in R:
        if r["cond"] == "unknown_id_fallback" or r.get("seed", 0) != 0: continue
        c = r["cond"] + ("[random]" if r.get("basis") == "random" else "")
        T[(f"{r['t']}|{r['q']}", c, r.get("sender") or "-")].append(0 if r.get("covered") == 0 else (r["correct"] or 0))
    tasks = sorted({k[0] for k in T})
    md += [f"## Receiver {rk}: end-to-end accuracy by condition (seed 0, pca unless marked; sender=smol shown for sender-specific conditions, qwen-sender values in tables5.json)", "",
           "| condition | " + " | ".join(tasks) + " |", "|---|" + "---|" * len(tasks)]
    for c in CONDS:
        cells = []
        for t in tasks:
            v = T.get((t, c, "smol")) or T.get((t, c, "-"))
            cells.append(f"{sum(v)/len(v):.3f} (n={len(v)})" if v else "-")
        md.append(f"| {c} | " + " | ".join(cells) + " |")
    md.append("")
md += ["## J-lens basis status", "", "DROPPED for this v5 execution (amendment v5.5). Qwen2.5-3B J-gram was infeasible on the laptop: fp32 backward peaked at 17.5 GB (over the 15 GB budget), and the bf16 run was killed after 98 min with no batch done. states_qwen.pt has no J-lens basis, so negotiate5 built only pca and random books. No jlens rows exist in any test file.", ""]
open(os.path.join(O, "EXTRA_TABLES_v5.md"), "w").write("\n".join(md)); print("\n".join(md))
